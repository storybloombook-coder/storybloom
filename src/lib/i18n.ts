/** Russian has 3 plural forms (1 / 2-4 / 5-20,0), cyclically after 20 --
 *  English's simple singular/plural doesn't map onto it, so every counted
 *  Russian string routes through this instead of a flat `n === 1 ? a : b`. */
function pluralRu(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few;
  return many;
}

function detectLocale(): Locale {
  const code = Localization.getLocales?.()[0]?.languageCode;
  return code === 'ru' ? 'ru' : 'en';
}

export const useLocaleStore = create<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
}>((set) => ({
  locale: detectLocale(),
  setLocale: (locale) => set({ locale }),
}));

/** Dot-path lookup into STRINGS[locale], e.g. t('page.cancel', 'ru'). Value
 *  can be a plain string or a function (for templates/pluralization) --
 *  pass extra args through `t(key, locale, ...args)` and they're forwarded
 *  to the function. Falls back to English, then the raw key, so a missing
 *  translation degrades instead of crashing. */
export function t(key: string, locale: Locale, ...args: unknown[]): string {
  const resolve = (table: unknown) => key.split('.').reduce(
    (node: unknown, part: string) => (node == null ? undefined : (node as Record<string, unknown>)[part]),
    table,
  );
  const value = resolve(STRINGS[locale]) ?? resolve(STRINGS.en) ?? key;
  if (typeof value === 'function') return (value as (...a: unknown[]) => string)(...args);
  return value as string;
}
